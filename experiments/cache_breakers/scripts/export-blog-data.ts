/**
 * Writes the blog post's data, so every number in it comes from
 * results/*.csv. Re-run after any results change:
 *
 *   OUT=<path to the post's data.ts> pnpm export-blog
 *
 * data.ts holds TABLE, the comparison (src/comparison.ts, the same rows and
 * words as the experiment page), and what the post's thread builder needs:
 * each API's cache rules (src/rules.ts), the sizes it draws a thread with,
 * and how its predictions fared against live threads (results/sequences).
 * The builder's engine and thread model are copied next to it verbatim
 * (engine.ts, threads.ts), so the post runs the code the tests check.
 *
 * Thread sizes are gpt-5.6-sol's, from the thread scenario: every request's
 * end is measured, and the split of each turn's growth into user message
 * and reply uses the fixture's word counts (~150 and ~500), as does the
 * split of the header into tools and system prompt (equal halves).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { median, toObs, type Obs } from "../src/analyze.js";
import { buildComparison, COLUMNS } from "../src/comparison.js";
import { parseCsv } from "../src/csv.js";
import { ADAPTERS } from "../src/providers/index.js";
import { buildRules, RULE_COLUMNS } from "../src/rules.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const OUT = process.env.OUT;
if (!OUT) throw new Error("Set OUT to the blog post's data.ts path");

function rows(scenario: string): Record<string, string>[] {
  const dir = path.join(root, "results", scenario);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".csv"))
    .flatMap((f) => parseCsv(fs.readFileSync(path.join(dir, f), "utf8")));
}

const allStatic: Obs[] = rows("static").map(toObs);
const threadRows = rows("thread");

// --- the comparison table -------------------------------------------------

const TABLE = buildComparison(allStatic, threadRows).map((row) => ({
  id: row.id,
  group: row.group,
  text: row.text,
  cells: Object.fromEntries(
    COLUMNS.map((c) => [
      c,
      {
        text: row.cells[c].text,
        status: row.cells[c].status,
        tier: row.cells[c].tier,
      },
    ])
  ),
}));

// --- the thread builder ---------------------------------------------------

const RULES = buildRules(allStatic);

const TOOL_COLUMNS = RULE_COLUMNS.map((column) => {
  const a = ADAPTERS[column]!;
  return { column, model: a.defaultModel, sibling: a.altModel };
});

// Request k's end, median over sol's thread trials (the read is 3 short).
const solThread = threadRows.filter(
  (r) => r.provider === "openai_responses" && !r.error
);
const ends = [0, 1].map(
  (k) => median(solThread.map((r) => Number(r.request_tokens!.split(";")[k]) - 3))!
);
const USER = Math.round((ends[1]! - ends[0]!) * (160 / 660));
const REPLY = Math.round(ends[1]! - ends[0]! - USER);
const HEADER = Math.round(ends[0]! - USER);
const SIZES = {
  tools: Math.round(HEADER / 2),
  system: HEADER - Math.round(HEADER / 2),
  user: USER,
  reply: REPLY,
};

// A prediction agrees within max(40, 1.5%) tokens (scripts/run-sequences.ts).
// The first request of a thread is left out: nothing is cached yet. So is
// a response whose usage reported 0 input tokens (it measured nothing).
const sequenceRows = rows("sequences").filter(
  (r) =>
    !r.error &&
    r.step !== "0" &&
    r.cached !== "" &&
    r.predicted !== "" &&
    r.input !== "0"
);
const VALIDATION = Object.fromEntries(
  RULE_COLUMNS.map((column) => {
    const mine = sequenceRows.filter((r) => r.provider === column);
    const agree = mine.filter(
      (r) =>
        Math.abs(Number(r.cached) - Number(r.predicted)) <=
        Math.max(40, 0.015 * Number(r.input))
    ).length;
    const threads = new Set(mine.map((r) => `${r.batch}/${r.run}`)).size;
    return [column, { threads, requests: mine.length, agree }];
  })
);

// --- write ------------------------------------------------------------------

const ts = `// Generated by experiments/cache_breakers/scripts/export-blog-data.ts from
// the experiment's results CSVs. Do not edit by hand; re-run the script.
import type { Rules } from "./engine";

export type Column = ${COLUMNS.map((c) => JSON.stringify(c)).join(" | ")};

export type TableRow = {
  id: string;
  group: string;
  /** May contain \`code\` spans. */
  text: string;
  cells: Record<
    Column,
    { text: string; status: "tested" | "n/a" | "not tested"; tier: string | null }
  >;
};

export const TABLE: TableRow[] = ${JSON.stringify(TABLE, null, 2)};

/** The APIs the thread builder predicts, with each one's sibling model. */
export const TOOL_COLUMNS: { column: string; model: string; sibling: string }[] = ${JSON.stringify(TOOL_COLUMNS, null, 2)};

/** Each API's cache rules, read from the static results. */
export const RULES: Record<string, Rules> = ${JSON.stringify(RULES, null, 2)};

/** Tokens per part, measured on gpt-5.6-sol's thread trials. */
export const SIZES = ${JSON.stringify(SIZES, null, 2)};

/** Live threads per API, and how many requests the engine predicted. */
export const VALIDATION: Record<
  string,
  { threads: number; requests: number; agree: number }
> = ${JSON.stringify(VALIDATION, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts);

// The engine and thread model, verbatim apart from extensionless imports.
const banner = (name: string) =>
  `// Copied from experiments/cache_breakers/src/${name} by\n// scripts/export-blog-data.ts. Do not edit here; edit the source and re-run.\n`;
for (const name of ["engine.ts", "threads.ts"]) {
  const src = fs
    .readFileSync(path.join(root, "src", name), "utf8")
    .replace(/from "\.\/(\w+)\.js"/g, 'from "./$1"');
  fs.writeFileSync(path.join(path.dirname(OUT), name), banner(name) + src);
}
console.log(
  `wrote ${OUT}: ${TABLE.length} rows, rules for ${RULE_COLUMNS.length} APIs; ` +
    Object.entries(VALIDATION)
      .map(([c, v]) => `${c} ${v.agree}/${v.requests}`)
      .join(", ")
);
